export default function MobileBottomNav({ role }) {
  const pathname = usePathname();

  const items = role === 'admin' ? ADMIN_BOTTOM
    : role === 'vendor' ? VENDOR_BOTTOM
    : role === 'retailer' ? RETAILER_BOTTOM
    : CUSTOMER_BOTTOM;

  const isActive = (href) => {
    if (href === '/vendor-dashboard' || href === '/admin-dashboard' || href === '/retailer-dashboard' || href === '/account') {
      return pathname === href;
    }
    return pathname.startsWith(href);
  };

  return (
    <nav className="lg:hidden fixed bottom-0 left-0 right-0 z-40 bg-white border-t border-gray-200 px-2 py-1.5 flex items-center justify-around shadow-[0_-2px_10px_rgba(0,0,0,0.05)]">
      {items.map((item) => {
        const active = isActive(item.href);
        return (
          <Link
            key={item.key}
            href={item.href}
            className={`flex flex-col items-center justify-center gap-0.5 py-1.5 px-2 rounded-lg transition-colors min-w-[56px] ${
              active
                ? 'text-ob-purple'
                : 'text-gray-400 hover:text-gray-600'
            }`}
          >
            <svg
              className={`w-5 h-5 transition-transform ${active ? 'scale-110' : ''}`}
              fill="none"
              stroke="currentColor"
              viewBox="0 0 24 24"
            >
              <path
                strokeLinecap="round"
                strokeLinejoin="round"
                strokeWidth={active ? 2 : 1.5}
                d={item.icon}
              />
            </svg>
            <span className={`text-[10px] font-medium ${active ? 'font-semibold' : ''}`}>
              {item.label}
            </span>
          </Link>
        );
      })}
    </nav>
  );
}
